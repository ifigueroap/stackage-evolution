def check_processed_lts():
    """Check which LTS versions already have monad columns"""
    data_path = Path('../data/dfs')
    lts_folders = [f.name.replace('lts-', '') for f in data_path.glob('lts-*') if f.is_dir()]
    lts_folders = sorted(lts_folders, key=lambda x: [int(i) for i in x.split('-')])
    
    processed = []
    for lts in lts_folders:
        files_path = f'../data/dfs/lts-{lts}/lts-{lts}-files.df'
        if os.path.exists(files_path):
            try:
                df = pd.read_pickle(files_path)
                monad_cols = [c for c in df.columns if 'Control.Monad' in c]
                if monad_cols:
                    processed.append(lts)
            except:
                pass
    
    print(f"📊 LTS versions with monad columns: {len(processed)}")
    print(f"   {processed[:10]}...")
    return processed


def clean_duplicates(lts):
    """Remove duplicate columns from files DataFrame"""
    files_path = f'../data/dfs/lts-{lts}/lts-{lts}-files.df'
    if not os.path.exists(files_path):
        return False
    
    df = pd.read_pickle(files_path)
    duplicates = df.columns[df.columns.duplicated()].tolist()
    
    if duplicates:
        print(f"  🧹 LTS {lts}: Removing {len(duplicates)} duplicates: {duplicates}")
        df = df.loc[:, ~df.columns.duplicated(keep='first')]
        df.to_pickle(files_path)
        return True
    return False

def clean_all_lts():
    """Clean duplicates from all LTS versions"""
    lts_list = get_lts_list_from_csv()
    print(f"🧹 Cleaning duplicates for {len(lts_list)} LTS versions...")
    
    cleaned = 0
    for lts in lts_list:
        if clean_duplicates(lts):
            cleaned += 1
    
    print(f"✅ Cleaned {cleaned} LTS versions")

